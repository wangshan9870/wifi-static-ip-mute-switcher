let home = "a4:91:b1:0c:22:7e"
let other = "02:11:22:33:44:55"
import Foundation
expect(HomeSettings.defaultRouter.isEmpty && HomeSettings.defaultIP.isEmpty, "new installations require setup")
func expect(_ value: Bool, _ message: String) { if !value { fatalError(message) } }
var p = NetworkPolicy()
expect(p.observe(network: home, homeNetwork: home, enabled: true) == nil, "debounce home")
expect(p.observe(network: home, homeNetwork: home, enabled: true) == .home, "home mode")
expect(p.observe(network: nil, homeNetwork: home, enabled: true) == nil, "unknown is not away")
expect(p.observe(network: other, homeNetwork: home, enabled: true) == nil, "debounce away")
expect(p.observe(network: other, homeNetwork: home, enabled: true) == .dhcp, "away restores DHCP")
expect(p.observe(network: home, homeNetwork: home, enabled: false) == nil, "paused")
expect(p.observe(network: home, homeNetwork: home, enabled: true) == nil, "pause resets debounce")
expect(p.observe(network: "", homeNetwork: home, enabled: true) == nil, "empty is unknown")
expect(p.observe(network: "a4:91:b1:0c:22:7f", homeNetwork: home, enabled: true) == nil, "exact match debounce")
expect(p.observe(network: "a4:91:b1:0c:22:7f", homeNetwork: home, enabled: true) == .dhcp, "no prefix match")
print("Policy tests passed (10 checks)")
expect(!SpeakerPolicy.shouldMute(network: home, homeNetwork: home, enabled: true), "home leaves sound alone")
expect(SpeakerPolicy.shouldMute(network: other, homeNetwork: home, enabled: true), "away mutes")
expect(SpeakerPolicy.shouldMute(network: nil, homeNetwork: home, enabled: true), "unknown protects speakers")
expect(SpeakerPolicy.shouldMute(network: "", homeNetwork: home, enabled: true), "disconnected protects speakers")
expect(SpeakerPolicy.shouldMute(network: "a4:91:b1:0c:22:7f", homeNetwork: home, enabled: true), "speaker home match is exact")
expect(!SpeakerPolicy.shouldMute(network: other, homeNetwork: home, enabled: false), "independent protection switch")
expect(!SpeakerPolicy.shouldMute(network: nil, homeNetwork: home, enabled: false), "disabled never acts")
expect(SpeakerPolicy.isInternalSpeaker(transport: 1651274862, source: 1769173099), "this Mac internal speakers")
expect(!SpeakerPolicy.isInternalSpeaker(transport: 0x626C746E, source: 0x6864706E), "wired headphones excluded")
expect(!SpeakerPolicy.isInternalSpeaker(transport: 0x626C7565, source: 0x6973706B), "Bluetooth excluded")
expect(!SpeakerPolicy.isInternalSpeaker(transport: 0x68646D69, source: 0x6973706B), "HDMI excluded")
expect(!SpeakerPolicy.isInternalSpeaker(transport: nil, source: nil), "unidentified devices excluded")
print("Speaker policy tests passed (12 checks)")
var transition = SpeakerTransitionPolicy()
expect(transition.desiredMute(network: other, homeNetwork: home, enabled: true) == true, "away enforces mute")
expect(transition.desiredMute(network: home, homeNetwork: home, enabled: true) == nil, "first home observation waits")
expect(transition.desiredMute(network: home, homeNetwork: home, enabled: true) == false, "arrival restores sound")
expect(transition.desiredMute(network: home, homeNetwork: home, enabled: true) == false, "failed restore retries")
transition.didRestoreHome()
expect(transition.desiredMute(network: home, homeNetwork: home, enabled: true) == nil, "manual mute at home is respected")
expect(transition.desiredMute(network: nil, homeNetwork: home, enabled: true) == true, "unknown mutes and rearms")
expect(transition.desiredMute(network: home, homeNetwork: home, enabled: true) == nil, "return waits again")
expect(transition.desiredMute(network: home, homeNetwork: home, enabled: true) == false, "second return restores again")
transition.didRestoreHome()
expect(transition.desiredMute(network: nil, homeNetwork: home, enabled: false) == nil, "disabled does not act")
expect(transition.desiredMute(network: home, homeNetwork: home, enabled: true) == nil, "reenabling confirms home")
expect(transition.desiredMute(network: home, homeNetwork: home, enabled: true) == false, "reenabling restores home")
var startup = SpeakerTransitionPolicy()
expect(startup.desiredMute(network: home, homeNetwork: home, enabled: true) == nil, "startup home confirms")
expect(startup.desiredMute(network: home, homeNetwork: home, enabled: true) == false, "startup home unmutes")
expect(startup.desiredMute(network: "a4:91:b1:0c:22:7f", homeNetwork: home, enabled: true) == true, "similar router mutes")
expect(startup.desiredMute(network: "", homeNetwork: home, enabled: true) == true, "empty network mutes")
print("Home restoration tests passed (15 checks)")

expect(HomeSettings.validRouter(home), "normalized router accepted")
expect(!HomeSettings.validRouter("A4:91:B1:0C:22:7E"), "stored router must be normalized")
expect(!HomeSettings.validRouter(""), "empty router rejected")
expect(HomeSettings.validIP("192.168.50.42"), "private IPv4 accepted")
expect(HomeSettings.validIP("10.0.0.42"), "custom IP accepted")
