let wifi: [String: Any] = ["InterfaceName": "en0", "Router": "192.168.1.1", "ARPResolvedIPAddress": "192.168.1.1", "ARPResolvedHardwareAddress": "A4:91:B1:0C:22:7E"]
let vpn: [String: Any] = ["InterfaceName": "utun4", "Router": "100.77.93.84"]
expect(GatewayParser.observe(services: [vpn, wifi], interface: "en0") == .network(mac: home, router: "192.168.1.1"), "Wi-Fi gateway MAC from configd state")
expect(GatewayParser.observe(services: [vpn], interface: "en0") == .disconnected, "other interfaces ignored")
expect(GatewayParser.observe(services: [], interface: "en0") == .disconnected, "no service is disconnected")
